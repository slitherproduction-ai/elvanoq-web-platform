"""Build the browser dictionary and refresh language asset URLs on every portal page."""
import json, hashlib, re
from pathlib import Path
root=Path(__file__).resolve().parents[1]/'dist'
data=json.loads((root/'i18n-en.json').read_text())
(root/'i18n-en.js').write_text('/* Generated by scripts/build-i18n.py */\nwindow.ELVANOQ_EN='+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n')
assets={name:hashlib.sha256((root/name).read_bytes()).hexdigest()[:10] for name in ['i18n.css','i18n-en.js','i18n.js']}
for p in root.rglob('*.html'):
 s=p.read_text()
 s=re.sub(r'<link rel="stylesheet" href="/i18n.css[^\"]*">|<script src="/i18n(?:-en)?.js[^\"]*" defer></script>','',s)
 tags=f'<link rel="stylesheet" href="/i18n.css?v={assets["i18n.css"]}"><script src="/i18n-en.js?v={assets["i18n-en.js"]}" defer></script><script src="/i18n.js?v={assets["i18n.js"]}" defer></script>'
 s=s.replace('</head>',tags+'</head>')
 p.write_text(s)
